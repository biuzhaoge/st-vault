import { afterEach, describe, expect, it, vi } from 'vitest';
import { mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { SqlDatabase } from './sql.js';
import { EmbeddedPostgres } from './embedded.js';
import { PortableTransactions } from './portable-transactions.js';
import type { PortableCheckpoint } from './portable-checkpoint.js';
import { atomicJson } from '../library/files.js';

const cleanup: (() => Promise<void>)[] = [];
afterEach(async () => {
  for (const action of cleanup.splice(0).reverse()) await action();
  vi.unstubAllEnvs();
});
describe.skipIf(process.env.STV_TEST_POSTGRES !== '1')('portable PostgreSQL checkpoints', () => {
  async function fixture() {
    const root = await mkdtemp(path.join(tmpdir(), 'stv-pg-checkpoint-'));
    cleanup.push(() => rm(root, { recursive: true, force: true }));
    const server = await EmbeddedPostgres.open({
      root,
      binaries: process.env.STV_POSTGRES_BIN ?? '/usr/lib/postgresql/18/bin',
    });
    cleanup.push(() => server.close());
    vi.stubEnv('STV_DATABASE_SOCKET', server.connection.host);
    if (typeof server.connection.password !== 'string')
      throw Error('TEST_DATABASE_PASSWORD_REQUIRED');
    vi.stubEnv('STV_DATABASE_PASSWORD', server.connection.password);
    const databases: SqlDatabase[] = [];
    cleanup.push(async () => {
      for (const db of databases) await db.close();
    });
    const journals: PortableTransactions[] = [];
    cleanup.push(async () => {
      for (const journal of journals) await journal.close();
    });
    const media = path.join(root, 'media'),
      libraryId = randomUUID();
    let manifest: { checkpoint?: PortableCheckpoint; previous?: PortableCheckpoint } = {};
    let fault: ((point: string) => void | Promise<void>) | undefined;
    let namespace = 0;
    const database = async () => {
      const db = await SqlDatabase.open(path.join(root, `hot-${namespace++}`));
      databases.push(db);
      await db.exec(`CREATE TABLE parents(id TEXT PRIMARY KEY,value TEXT NOT NULL);
        CREATE TABLE children(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          parent TEXT NOT NULL REFERENCES parents(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
          value TEXT NOT NULL);
        CREATE TABLE private_config(id TEXT PRIMARY KEY,value TEXT NOT NULL);
        INSERT INTO private_config VALUES('secret','SOURCE_PRIVATE');`);
      return db;
    };
    const journal = async (db: SqlDatabase, published = manifest) => {
      const journal = await PortableTransactions.open(db.postgres, {
        mediaRoot: media,
        libraryId,
        tables: ['children', 'parents'],
        ...published,
        fault: (point) => fault?.(point),
        publishCheckpoint: (checkpoint, previous) => {
          manifest = { checkpoint, previous };
          atomicJson(path.join(media, 'manifest.json'), manifest);
        },
      });
      journals.push(journal);
      return journal;
    };
    return {
      media,
      libraryId,
      database,
      journal,
      setFault(callback?: typeof fault) {
        fault = callback;
      },
      get manifest() {
        return manifest;
      },
    };
  }

  it('retries an interrupted zero-sequence cold restore, including an old unmarked hot database', async () => {
    const f = await fixture();
    const source = await f.database();
    await source.exec("INSERT INTO parents VALUES('p','migrated')");
    const journal = await f.journal(source);
    await journal.checkpoint();
    await journal.close();
    expect(f.manifest.checkpoint?.sequence).toBe(0);
    const file = path.join(f.media, f.manifest.checkpoint!.file);
    const original = await readFile(file);
    for (const legacy of [false, true]) {
      const cold = await f.database();
      if (legacy) {
        await cold.exec(
          'CREATE TABLE stv_library_state(id SMALLINT PRIMARY KEY CHECK(id=1),library UUID NOT NULL,sequence BIGINT NOT NULL)',
        );
        await cold.prepare('INSERT INTO stv_library_state VALUES(1,?,0)').run(f.libraryId);
      }
      await writeFile(file, 'temporarily unreadable checkpoint');
      await expect(f.journal(cold)).rejects.toThrow('PORTABLE_CHECKPOINT_CORRUPT');
      await writeFile(file, original);
      const restored = await f.journal(cold);
      expect(await cold.prepare('SELECT value FROM parents').get()).toEqual({ value: 'migrated' });
      await restored.close();
      // Once restored, an ordinary hot restart at the same sequence can use its projection.
      await writeFile(file, 'temporarily unreadable checkpoint');
      await (await f.journal(cold)).close();
      await writeFile(file, original);
    }
  }, 30000);

  it('repairs an unmarked positive hot sequence from checkpoint zero and its complete journal, preserving the hot data on failure', async () => {
    const f = await fixture(),
      source = await f.database();
    await source.exec(
      "INSERT INTO parents VALUES('base','from old library'); INSERT INTO children(id,parent,value) VALUES(100,'base','historical child')",
    );
    const journal = await f.journal(source);
    await journal.checkpoint();
    await journal.transaction(() =>
      source.exec(
        "INSERT INTO parents VALUES('later','after cutover'); INSERT INTO children(id,parent,value) VALUES(101,'later','new child')",
      ),
    );
    await journal.close();
    const hot = await f.database();
    // Older builds could admit new writes after skipping the missing baseline.
    await hot.exec(`CREATE TABLE stv_library_state(id SMALLINT PRIMARY KEY,library UUID NOT NULL,sequence BIGINT NOT NULL);
      INSERT INTO parents VALUES('later','after cutover'); INSERT INTO children(id,parent,value) VALUES(101,'later','new child');`);
    await hot.prepare('INSERT INTO stv_library_state VALUES(1,?,1)').run(f.libraryId);
    const read = () => hot.prepare('SELECT id,value FROM parents ORDER BY id').all();
    const log = path.join(f.media, 'postgres-journal', 'active.log');
    const tail = await readFile(log);
    const checkpoint = path.join(f.media, f.manifest.checkpoint!.file);
    const base = await readFile(checkpoint);
    await writeFile(checkpoint, 'unavailable');
    await expect(f.journal(hot)).rejects.toThrow('PORTABLE_CHECKPOINT_CORRUPT');
    expect(await read()).toEqual([{ id: 'later', value: 'after cutover' }]);
    await writeFile(checkpoint, base);
    await writeFile(log, tail.subarray(0, 20));
    await expect(f.journal(hot)).rejects.toThrow('PORTABLE_JOURNAL_BEHIND_DATABASE');
    expect(await read()).toEqual([{ id: 'later', value: 'after cutover' }]);
    expect(await readFile(log)).toEqual(tail.subarray(0, 20));
    expect(await hot.prepare('SELECT sequence FROM stv_library_state').get()).toEqual({
      sequence: 1,
    });
    await writeFile(log, tail);
    const fixed = await f.journal(hot);
    expect(await read()).toEqual([
      { id: 'base', value: 'from old library' },
      { id: 'later', value: 'after cutover' },
    ]);
    expect(fixed.status()).toMatchObject({ sequence: 1, replayed: 1 });
    await fixed.close();
    await writeFile(checkpoint, 'temporarily unavailable');
    const healthy = await f.journal(hot);
    expect(healthy.status()).toMatchObject({ sequence: 1, replayed: 0 });
    expect(
      await healthy.transaction(() =>
        hot.prepare("INSERT INTO children(parent,value) VALUES('later','next') RETURNING id").get(),
      ),
    ).toEqual({ id: 102 });
  }, 30000);

  it('rebuilds an old incomplete first positive checkpoint from its retained zero ancestor and sealed frames', async () => {
    const f = await fixture(),
      hot = await f.database();
    await hot.exec("INSERT INTO parents VALUES('base','legacy')");
    const writer = await f.journal(hot);
    await writer.checkpoint();
    await writer.transaction(() => hot.exec("INSERT INTO parents VALUES('later','post-upgrade')"));
    // Reproduce the old projection that skipped the initial checkpoint while keeping its actual tail.
    await hot.transaction(async () => {
      await hot.exec("SET LOCAL stv.replay='on'");
      await hot.exec("DELETE FROM parents WHERE id='base'");
    });
    await writer.checkpoint();
    await writer.close();
    expect(f.manifest).toMatchObject({ checkpoint: { sequence: 1 }, previous: { sequence: 0 } });
    // Historical manifests had no provenance marker on the newly published checkpoint.
    delete f.manifest.checkpoint!.baselineVerified;
    atomicJson(path.join(f.media, 'manifest.json'), f.manifest);
    const historical = JSON.parse(
      await readFile(path.join(f.media, 'manifest.json'), 'utf8'),
    ) as typeof f.manifest;
    const firstPositive = f.manifest.checkpoint!.file;
    expect(await readFile(path.join(f.media, firstPositive), 'utf8')).not.toContain('legacy');
    await hot.exec('ALTER TABLE stv_library_state DROP COLUMN recovered');
    const sealed = path.join(f.media, 'postgres-journal', '1-1.log');
    const frame = await readFile(sealed);
    await rm(sealed);
    await expect(f.journal(hot)).rejects.toThrow('PORTABLE_JOURNAL_BEHIND_DATABASE');
    expect(await hot.prepare('SELECT id FROM parents ORDER BY id').all()).toEqual([
      { id: 'later' },
    ]);
    await writeFile(sealed, frame);
    const restored = await f.journal(hot);
    expect(await hot.prepare('SELECT id FROM parents ORDER BY id').all()).toEqual([
      { id: 'base' },
      { id: 'later' },
    ]);
    expect(restored.status()).toMatchObject({ sequence: 1, replayed: 1 });
    expect(restored.needsCheckpoint()).toBe(false);
    expect(f.manifest.checkpoint!.file).not.toBe(firstPositive);
    expect(f.manifest.checkpoint!.baselineVerified).toBe(true);
    expect(await readFile(path.join(f.media, f.manifest.checkpoint!.file), 'utf8')).toContain(
      'legacy',
    );
    await restored.close();
    const cold = await f.database();
    await (await f.journal(cold, historical)).close();
    expect(await cold.prepare('SELECT id FROM parents ORDER BY id').all()).toEqual([
      { id: 'base' },
      { id: 'later' },
    ]);
    const verified = JSON.parse(
      await readFile(path.join(f.media, 'manifest.json'), 'utf8'),
    ) as typeof f.manifest;
    expect(verified.checkpoint?.baselineVerified).toBe(true);
    // A current, self-contained repaired checkpoint remains usable by a new database
    // after the fallback file is lost. No existing hot data is at risk in this path.
    await rm(path.join(f.media, f.manifest.previous!.file));
    const standalone = await f.database();
    await (await f.journal(standalone, verified)).close();
    expect(await standalone.prepare('SELECT id FROM parents ORDER BY id').all()).toEqual([
      { id: 'base' },
      { id: 'later' },
    ]);
  }, 30000);

  it('streams foreign-key rows, retains fallback logs, restores a cold database and advances identity sequences', async () => {
    const f = await fixture(),
      db = await f.database();
    await db.exec(
      "INSERT INTO parents VALUES('p','base');INSERT INTO children(parent,value) SELECT 'p','row-'||n::text FROM generate_series(1,520) n",
    );
    let journal = await f.journal(db);
    expect(journal.needsCheckpoint()).toBe(true);
    await journal.checkpoint();
    expect(f.manifest.checkpoint?.sequence).toBe(0);
    await journal.transaction(async () => {
      await db.exec(
        "UPDATE parents SET value='changed';INSERT INTO children(parent,value) VALUES('p','new-521')",
      );
    });
    await journal.checkpoint();
    expect(await readdir(path.join(f.media, 'postgres-journal'))).toContain('1-1.log');
    await journal.transaction(async () => {
      await db.exec(
        "DELETE FROM children WHERE id=1;INSERT INTO children(parent,value) VALUES('p','new-522')",
      );
    });
    await journal.checkpoint();
    expect(f.manifest).toMatchObject({ checkpoint: { sequence: 2 }, previous: { sequence: 1 } });
    expect(await readdir(path.join(f.media, 'postgres-journal'))).not.toContain('1-1.log');
    expect(await readdir(path.join(f.media, 'postgres-journal'))).toContain('2-2.log');
    expect(
      (await readdir(path.join(f.media, 'catalog'))).filter((name) => name.endsWith('.ndjson')),
    ).toHaveLength(2);
    const contents = await readFile(path.join(f.media, f.manifest.checkpoint!.file), 'utf8');
    expect(contents).not.toContain('SOURCE_PRIVATE');
    await journal.transaction(() => db.exec("UPDATE children SET value='tail' WHERE id=2"));
    await journal.close();
    const cold = await f.database();
    journal = await f.journal(cold);
    expect(await cold.prepare('SELECT count(*) AS count FROM children').get()).toEqual({
      count: 521,
    });
    expect(await cold.prepare('SELECT value FROM children WHERE id=2').get()).toEqual({
      value: 'tail',
    });
    expect(await cold.prepare('SELECT value FROM parents').get()).toEqual({ value: 'changed' });
    expect(journal.status()).toMatchObject({ sequence: 3, replayed: 1, requiresRecovery: false });
    let nextId: number | undefined;
    await journal.transaction(async () => {
      nextId = (await cold
        .prepare("INSERT INTO children(parent,value) VALUES('p','next') RETURNING id")
        .get<{ id: number }>())!.id;
    });
    expect(nextId).toBe(523);
  }, 30000);

  it('releases the writer before export and combines one coherent snapshot with concurrent journal commits', async () => {
    const f = await fixture(),
      db = await f.database();
    await db.exec("INSERT INTO parents VALUES('p','snapshot-base')");
    let journal = await f.journal(db);
    let entered!: () => void, release!: () => void;
    const ready = new Promise<void>((resolve) => {
      entered = resolve;
    });
    const gate = new Promise<void>((resolve) => {
      release = resolve;
    });
    f.setFault((point) => {
      if (point === 'after-checkpoint-pin') {
        entered();
        return gate;
      }
      return undefined;
    });
    const checkpoint = journal.checkpoint();
    try {
      await ready;
      await journal.transaction(() => db.exec("UPDATE parents SET value='concurrent-tail'"));
    } finally {
      release();
      await checkpoint;
    }
    expect(f.manifest.checkpoint?.sequence).toBe(0);
    expect(await readFile(path.join(f.media, f.manifest.checkpoint!.file), 'utf8')).toContain(
      'snapshot-base',
    );
    expect(await readFile(path.join(f.media, f.manifest.checkpoint!.file), 'utf8')).not.toContain(
      'concurrent-tail',
    );
    expect(journal.status().sequence).toBe(1);
    await journal.close();
    f.setFault();
    const cold = await f.database();
    journal = await f.journal(cold);
    expect(await cold.prepare('SELECT value FROM parents').get()).toEqual({
      value: 'concurrent-tail',
    });
    expect(journal.status()).toMatchObject({ sequence: 1, replayed: 1 });
  }, 30000);

  it('keeps writes available after an unpublished checkpoint failure and recovers through the previous artifact', async () => {
    const f = await fixture(),
      db = await f.database();
    await db.exec("INSERT INTO parents VALUES('p','base')");
    let journal = await f.journal(db);
    await journal.checkpoint();
    await journal.transaction(() => db.exec("UPDATE parents SET value='one'"));
    f.setFault((point) => {
      if (point === 'before-checkpoint-publish') throw Error('CHECKPOINT_PUBLISH_FAULT');
    });
    await expect(journal.checkpoint()).rejects.toThrow('CHECKPOINT_PUBLISH_FAULT');
    expect(journal.status()).toMatchObject({ checkpointFailed: true, requiresRecovery: false });
    expect(f.manifest.checkpoint?.sequence).toBe(0);
    await journal.transaction(() => db.exec("UPDATE parents SET value='two'"));
    f.setFault();
    await journal.checkpoint();
    expect(f.manifest).toMatchObject({ checkpoint: { sequence: 2 }, previous: { sequence: 0 } });
    expect(
      (await readdir(path.join(f.media, 'catalog'))).filter((name) => name.endsWith('.ndjson')),
    ).toHaveLength(2);
    await journal.transaction(() => db.exec("UPDATE parents SET value='three'"));
    await journal.checkpoint();
    expect(f.manifest.previous?.sequence).toBe(2);
    await writeFile(path.join(f.media, f.manifest.checkpoint!.file), 'corrupt checkpoint');
    await journal.close();
    const cold = await f.database();
    journal = await f.journal(cold);
    expect(await cold.prepare('SELECT value FROM parents').get()).toEqual({ value: 'three' });
    expect(journal.status()).toMatchObject({ sequence: 3, replayed: 1 });
    await journal.checkpoint();
    expect(journal.status().checkpointFailed).toBe(false);
  }, 30000);

  it('treats a manifest published before interruption as durable and preserves later journal commits', async () => {
    const f = await fixture(),
      db = await f.database();
    await db.exec("INSERT INTO parents VALUES('p','base')");
    let journal = await f.journal(db);
    await journal.checkpoint();
    await journal.transaction(() => db.exec("UPDATE parents SET value='published'"));
    f.setFault((point) => {
      if (point === 'after-checkpoint-publish') throw Error('AFTER_MANIFEST_FAULT');
    });
    await expect(journal.checkpoint()).rejects.toThrow('AFTER_MANIFEST_FAULT');
    expect(f.manifest.checkpoint?.sequence).toBe(1);
    await journal.transaction(() => db.exec("UPDATE parents SET value='later'"));
    await journal.close();
    f.setFault();
    const cold = await f.database();
    journal = await f.journal(cold);
    expect(await cold.prepare('SELECT value FROM parents').get()).toEqual({ value: 'later' });
    expect(journal.status()).toMatchObject({ sequence: 2, replayed: 1 });
  }, 30000);
});
